// Accuracy report: run the estimator on synthetic claps with known echo times
// and write docs/ACCURACY.md. Run with: npm run accuracy
import { writeFileSync } from 'node:fs';
import { analyzeClap } from '../src/dsp/analyze.ts';
import { synthClap } from '../src/dsp/synth.ts';

const RTS = [0.2, 0.3, 0.5, 0.7, 1.0, 1.5, 2.0];
const SNRS = [35, 45, 55];
const SEEDS = 10;
const FS = 48000;

/** The textbook shortcut: Schroeder-integrate to the end of the recording, no noise handling, fit -5..-25 dB. */
function naiveT20(x: Float32Array, fs: number): number | null {
  let peak = 0, at = 0;
  for (let i = 0; i < x.length; i++) if (Math.abs(x[i]) > peak) { peak = Math.abs(x[i]); at = i; }
  const n = x.length - at;
  const edc = new Float64Array(n);
  let acc = 0;
  for (let i = n - 1; i >= 0; i--) { acc += x[at + i] * x[at + i]; edc[i] = acc; }
  const xs: number[] = [], ys: number[] = [];
  for (let i = 0; i < n; i += 48) {
    const d = 10 * Math.log10(edc[i] / edc[0]);
    if (d <= -5 && d >= -25) { xs.push(i / fs); ys.push(d); }
    if (d < -25) break;
  }
  if (xs.length < 5) return null;
  const mx = xs.reduce((a, b) => a + b) / xs.length, my = ys.reduce((a, b) => a + b) / ys.length;
  let sxy = 0, sxx = 0;
  for (let i = 0; i < xs.length; i++) { sxy += (xs[i] - mx) * (ys[i] - my); sxx += (xs[i] - mx) ** 2; }
  const slope = sxy / sxx;
  return slope < 0 ? -60 / slope : null;
}

const pct = (v: number) => (v * 100).toFixed(1) + ' %';
function stats(errs: number[]) {
  const s = errs.slice().sort((a, b) => a - b);
  const mean = s.reduce((a, b) => a + b, 0) / Math.max(s.length, 1);
  return { mean, p90: s[Math.max(0, Math.ceil(s.length * 0.9) - 1)] ?? NaN, max: s[s.length - 1] ?? NaN };
}

const lines: string[] = [];
lines.push('# Clapback accuracy on synthetic claps');
lines.push('');
lines.push('Generated by `npm run accuracy` (`scripts/accuracy.ts`). Each case is a 2 ms clap burst convolved with a synthetic room');
lines.push('(Gaussian noise under an exponential decay that falls 60 dB in exactly RT60 seconds), plus pink background noise');
lines.push(`at a set level below the clap. ${SEEDS} different random rooms per cell, ${FS / 1000} kHz.`);
lines.push('');
lines.push('Error = |measured - true| / true for the headline echo time (mean of the 500 Hz, 1 kHz and 2 kHz octave bands).');
lines.push('');
lines.push('| True RT60 | Clap above noise | Mean error | 90th pct | Worst | No result | Textbook shortcut, mean error |');
lines.push('| --- | --- | --- | --- | --- | --- | --- |');

const all: Record<number, number[]> = {};
const naiveAll: Record<number, number[]> = {};
for (const snr of SNRS) {
  all[snr] = [];
  naiveAll[snr] = [];
  for (const rt of RTS) {
    const errs: number[] = [];
    const nerrs: number[] = [];
    let fails = 0;
    for (let s = 0; s < SEEDS; s++) {
      const x = synthClap({ rt60: rt, snrDb: snr, seed: 1000 * snr + 37 * s + Math.round(rt * 100), noise: 'pink', duration: Math.max(2, rt * 1.6 + 1) });
      const a = analyzeClap(x, FS);
      if (a.rt60 === null) fails++;
      else errs.push(Math.abs(a.rt60 - rt) / rt);
      const nv = naiveT20(x, FS);
      nerrs.push(nv === null ? 1 : Math.abs(nv - rt) / rt);
    }
    all[snr].push(...errs);
    naiveAll[snr].push(...nerrs);
    const st = stats(errs);
    lines.push(`| ${rt.toFixed(1)} s | ${snr} dB | ${pct(st.mean)} | ${pct(st.p90)} | ${pct(st.max)} | ${fails}/${SEEDS} | ${pct(stats(nerrs).mean)} |`);
  }
}
lines.push('');
lines.push('## Summary by clap loudness');
lines.push('');
lines.push('| Clap above noise | Mean error | 90th pct | Worst | Textbook shortcut, mean error |');
lines.push('| --- | --- | --- | --- | --- |');
for (const snr of SNRS) {
  const st = stats(all[snr]);
  lines.push(`| ${snr} dB | ${pct(st.mean)} | ${pct(st.p90)} | ${pct(st.max)} | ${pct(stats(naiveAll[snr]).mean)} |`);
}

// Frequency-dependent room.
const want: Record<number, number> = { 500: 1.1, 1000: 0.8, 2000: 0.6, 4000: 0.45 };
const bandErr: Record<number, number[]> = { 500: [], 1000: [], 2000: [], 4000: [] };
for (let s = 0; s < SEEDS; s++) {
  const a = analyzeClap(synthClap({ rt60: want, snrDb: 55, seed: 500 + s, noise: 'pink', duration: 3 }), FS);
  for (const b of a.bands) if (b.rt60 !== null) bandErr[b.fc].push(Math.abs(b.rt60 - want[b.fc]) / want[b.fc]);
}
lines.push('');
lines.push('## Per-band echo time in a room that is boomier in the bass');
lines.push('');
lines.push('True RT60: 1.1 s at 500 Hz, 0.8 s at 1 kHz, 0.6 s at 2 kHz, 0.45 s at 4 kHz; clap 55 dB above noise.');
lines.push('');
lines.push('| Band | Mean error | Worst |');
lines.push('| --- | --- | --- |');
for (const fc of [500, 1000, 2000, 4000]) {
  const st = stats(bandErr[fc]);
  lines.push(`| ${fc >= 1000 ? fc / 1000 + ' kHz' : fc + ' Hz'} | ${pct(st.mean)} | ${pct(st.max)} |`);
}
lines.push('');
lines.push('The higher bands read slightly long here because some of the longer bass decay leaks through the octave filters;');
lines.push('real octave-band meters have the same effect.');
lines.push('');
lines.push('## What this does not show');
lines.push('');
lines.push('These rooms are ideal diffuse fields. Real rooms have early reflections, flutter echoes between parallel walls and');
lines.push('decays that bend; a hand clap is not perfectly loud at every frequency; and phone microphones may filter the sound.');
lines.push('So treat a real-room reading as good to roughly ±10-20 %, which is enough to tell "dry" from "echoey" and to see');
lines.push('whether a change helped, but it is not a certified ISO 3382 measurement.');
writeFileSync('docs/ACCURACY.md', lines.join('\n') + '\n');
console.log(lines.join('\n'));
